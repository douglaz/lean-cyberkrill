"""Generate the nine digests with openssl, feeding exact bytes on stdin."""
import json
from pathlib import Path
import subprocess


def main():
    messages = [
        ("", 1), ("a", 1), ("abc", 1), ("message digest", 1),
        ("abcdefghijklmnopqrstuvwxyz", 1),
        ("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", 1),
        ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789", 1),
        ("1234567890", 8), ("a", 1_000_000),
    ]
    rows = []
    for message, repeat in messages:
        digest = subprocess.run(["openssl", "dgst", "-ripemd160", "-binary"],
                                input=message.encode("ascii") * repeat,
                                capture_output=True, check=True).stdout
        assert len(digest) == 20
        rows.append(dict(message=message, repeat=repeat, digest=digest.hex()))
    version = subprocess.run(["openssl", "version"], capture_output=True,
                             text=True, check=True).stdout.strip()
    fixture = dict(provenance="Generated by generate-ripemd160-vectors.py; message selection: "
                   "https://homes.esat.kuleuven.be/~bosselae/ripemd160.html",
                   openssl=version, vectors=rows)
    destination = Path(__file__).resolve().parent / "test-data/ripemd160.json"
    destination.write_text(json.dumps(fixture, indent=2) + "\n")
    print(f"RIPEMD-160 generated vectors: {len(rows)}/9; {version}")


if __name__ == "__main__":
    main()
